"""Regression tests for session message provenance."""

import json

from archaeology.extractors.sessions import extract_narrative, parse_session


def _write(path, entries):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(json.dumps(entry) + "\n" for entry in entries))


def _user(content, **fields):
    return {"type": "user", "entrypoint": "cli", "message": {"content": content}, **fields}


def test_injected_entries_are_filtered_and_human_text_is_preserved(tmp_path):
    path = tmp_path / "session.jsonl"
    entries = [
        _user("injected meta", isMeta=True),
        _user("injected compaction", isCompactSummary=True),
        _user("injected sidechain", isSidechain=True),
        _user("tool data", toolUseResult={"text": "injected"}),
        _user(
            "This session is being continued from a previous conversation and summarizes everything"
        ),
        _user("Stop hook feedback: ignored"),
        _user("Caveat: The messages below were generated by a command"),
        _user("<command-name>/goal</command-name><command-args>injected</command-args>"),
        _user("<task-notification>ignored</task-notification>"),
        _user("<local-command-stdout>ignored</local-command-stdout>"),
        _user("I want to design a meaningful feature."),
        _user("<system-reminder>hidden\ntext</system-reminder>Please improve the original design."),
        {"type": "assistant", "message": {"content": "I will improve the design."}},
    ]
    _write(path, entries)
    session = parse_session(str(path))
    assert [m["content"] for m in session["human_messages"]] == [
        "I want to design a meaningful feature.",
        "Please improve the original design.",
    ]
    assert all(m["provenance"] == "human" for m in session["human_messages"])
    assert all(m["provenance"] == "agent" for m in session["assistant_messages"])
    # The mixed system-reminder + prose entry counts once, as human (disjoint buckets).
    assert session["provenance_counts"]["harness"] == 10
    assert session["provenance_counts"]["human"] == 2
    narrative = extract_narrative(session)
    assert "harness" in narrative.lower()
    assert "<system-reminder>" not in narrative
    assert "<command-name>" not in narrative
    assert "This session is being continued" not in narrative


def test_sdk_and_subagent_sessions_do_not_produce_human_messages(tmp_path):
    for path, entry in [
        (tmp_path / "sdk.jsonl", _user("I want to make a decision.", entrypoint="sdk")),
        (tmp_path / "subagents" / "child.jsonl", _user("I want to make a decision.")),
    ]:
        _write(path, [entry])
        session = parse_session(str(path))
        assert session["agent_driven"] is True
        assert session["human_messages"] == []
        assert session["agent_messages"][0]["provenance"] == "agent"
        narrative = extract_narrative(session)
        assert "agent-driven" in narrative.lower()
        assert "**[Human]**" not in narrative


def test_tool_results_and_unclosed_injection_never_become_human_text(tmp_path):
    path = tmp_path / "session.jsonl"
    _write(
        path,
        [
            _user(
                [
                    {"type": "text", "text": "Please keep this request."},
                    {"type": "tool_result", "content": "injected output"},
                ]
            ),
            _user("<system-reminder>unfinished injected content"),
        ],
    )
    session = parse_session(str(path))
    assert [m["content"] for m in session["human_messages"]] == ["Please keep this request."]
    assert session["provenance_counts"] == {
        **session["provenance_counts"],
        "human": 1,
        "harness": 1,
    }
    assert "system-reminder" not in extract_narrative(session)


def test_filtered_agent_driven_session_keeps_its_provenance_header(tmp_path):
    path = tmp_path / "subagents" / "filtered.jsonl"
    _write(path, [_user("sidechain content", isSidechain=True)])
    session = parse_session(str(path))
    narrative = extract_narrative(session)
    assert "agent-driven" in narrative.lower()
    # Subagent sidechain content is agent provenance, not filtered harness.
    assert "0 human, 1 agent, 0 harness" in narrative.lower()


def test_filtered_sdk_session_is_still_agent_driven(tmp_path):
    path = tmp_path / "sdk.jsonl"
    _write(path, [_user("sdk sidechain", isSidechain=True, entrypoint="sdk")])
    session = parse_session(str(path))
    assert session["agent_driven"] is True
    assert "agent-driven" in extract_narrative(session).lower()


def test_sidechain_subagent_content_is_agent_provenance(tmp_path):
    path = tmp_path / "subagents" / "agent.jsonl"
    _write(
        path,
        [
            _user("Investigate this task", isSidechain=True),
            {
                "type": "assistant",
                "isSidechain": True,
                "message": {"content": "Investigation complete."},
            },
        ],
    )
    session = parse_session(str(path))
    narrative = extract_narrative(session)
    assert "Investigate this task" in narrative
    assert "Investigation complete." in narrative
    assert "**[Human]**" not in narrative
    assert session["provenance_counts"]["agent"] == 2


def test_unknown_and_interactive_entrypoints_remain_human(tmp_path):
    for entrypoint in ("ide", "desktop", "unknown"):
        path = tmp_path / f"{entrypoint}.jsonl"
        _write(path, [_user("Please preserve my request.", entrypoint=entrypoint)])
        session = parse_session(str(path))
        assert not session["agent_driven"]
        assert session["human_messages"]


def test_unfinished_tag_name_stays_in_human_prose(tmp_path):
    path = tmp_path / "session.jsonl"
    _write(path, [_user("I typed <command-name while writing prose.")])
    assert (
        parse_session(str(path))["human_messages"][0]["content"]
        == "I typed <command-name while writing prose."
    )


def test_counts_are_disjoint_for_mixed_content(tmp_path):
    path = tmp_path / "session.jsonl"
    _write(
        path,
        [
            _user("<system-reminder>hidden</system-reminder>Please keep my request."),
            _user("tool output", toolUseResult={"x": 1}),
        ],
    )
    counts = parse_session(str(path))["provenance_counts"]
    assert sum(counts.values()) == 2
    assert counts["human"] == 1 and counts["harness"] == 1


def test_malformed_message_does_not_drop_valid_entries(tmp_path):
    path = tmp_path / "session.jsonl"
    _write(path, [_user("ignored", message="bad"), _user("Please keep this valid request.")])
    session = parse_session(str(path))
    assert session["human_messages"][0]["content"] == "Please keep this valid request."
    assert session["provenance_counts"]["malformed"] == 1


def test_bash_and_local_command_output_are_harness(tmp_path):
    path = tmp_path / "session.jsonl"
    tags = (
        "bash-stdout",
        "bash-input",
        "bash-stderr",
        "local-command-stdout",
        "local-command-stderr",
    )
    _write(
        path,
        [_user(f"<{tag}>synthetic output</{tag}>") for tag in tags]
        + [_user("<pasted_content>my own words</pasted_content>")],
    )
    session = parse_session(str(path))
    assert len(session["human_messages"]) == 1
    assert "pasted_content" in session["human_messages"][0]["content"]
    assert session["provenance_counts"]["harness"] == len(tags)


def test_adversarial_tags_finish_within_one_second(tmp_path):
    import subprocess
    import sys

    path = tmp_path / "session.jsonl"
    _write(path, [_user("<command-x>" * 95000)])
    result = subprocess.run(
        [
            sys.executable,
            "-c",
            "from archaeology.extractors.sessions import parse_session; import sys; parse_session(sys.argv[1])",
            str(path),
        ],
        timeout=1,
        capture_output=True,
    )
    assert result.returncode == 0


