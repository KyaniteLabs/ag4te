def test_include_subagents_cli_extracts_sidechain_content(tmp_path, monkeypatch):
    import os
    from pathlib import Path

    from click.testing import CliRunner

    from archaeology import cli

    monkeypatch.chdir(tmp_path)
    monkeypatch.setenv("PYTHONPATH", str(Path(cli.__file__).resolve().parent.parent))
    (tmp_path / "projects/demo/data").mkdir(parents=True)
    sessions = tmp_path / "sessions"
    _write(
        sessions / "subagents/agent.jsonl",
        [_user("Investigate the synthetic task", isSidechain=True)],
    )
    result = CliRunner().invoke(
        cli.main,
        ["extract-sessions", "demo", "--sessions-dir", os.fspath(sessions), "--include-subagents"],
    )
    assert result.exit_code == 0, result.output
    narrative = (tmp_path / "projects/demo/data/raw-sessions.md").read_text()
    assert "**[Agent]** Investigate the synthetic task" in narrative
    assert "**[Human]**" not in narrative


def test_subagents_folder_above_the_scan_root_does_not_mark_sessions(tmp_path, monkeypatch):
    sessions = tmp_path / "subagents" / "sessions"
    path = sessions / "-work-demo" / "s.jsonl"
    path.parent.mkdir(parents=True)
    path.write_text(json.dumps(_user("I want to make a decision.")) + "\n")
    session = parse_session(str(path), str(sessions))
    assert not session["agent_driven"]
    assert session["provenance_counts"]["human"] == 1
    child = sessions / "-work-demo" / "s" / "subagents" / "agent-1.jsonl"
    child.parent.mkdir(parents=True)
    child.write_text(json.dumps(_user("I want to make a decision.")) + "\n")
    assert parse_session(str(child), str(sessions))["agent_driven"]


def test_scanning_a_subagents_folder_directly_still_marks_its_files(tmp_path):
    child = tmp_path / "-work-demo" / "s" / "subagents" / "agent-1.jsonl"
    child.parent.mkdir(parents=True)
    child.write_text(json.dumps(_user("I want to make a decision.")) + "\n")
    assert parse_session(str(child), str(child.parent))["agent_driven"]


